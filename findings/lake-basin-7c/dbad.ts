// Where the badwater in the start's view comes from: npx tsx .scratch/dbad.ts <seed>
import { generate } from "../src/core/gen/generate";
import { makeSpec } from "../src/core/spec/mapspec";
import { surfaceOf } from "../src/core/format/world";
import { mapObjects } from "../src/core/sim/model";
import { startOfObjects } from "../src/core/analysis/easyStart";
import { tilesInFrame, openingFrame } from "../src/core/analysis/opening";
const seed = Number(process.argv[2]);
const spec = makeSpec({ seed, theme: "lakeBasin", size: { x: 256, y: 256 }, designedFor: "normal" as never });
const r = generate(spec);
const W = 256, H = 256;
const heights = surfaceOf(r.file.world);
const st = startOfObjects(mapObjects(r.file.world), heights, W)!;
const D = r.built.settle.depth, C = r.built.settle.contamination;
const fr = openingFrame({ x: st.x, y: st.y, z: st.level, orientation: st.orientation }, W, H, { heights });
const inView: number[] = [];
for (let i = 0; i < W * H; i++) if (D[i] >= 0.1 && C[i] > 0.05 && fr.mask[i]) inView.push(i);
const xs = inView.map((i) => i % W), ys = inView.map((i) => Math.floor(i / W));
console.log("start", st.x, st.y, st.level, "orient", st.orientation, "badInView", inView.length, inView.length ? `bbox x${Math.min(...xs)}-${Math.max(...xs)} y${Math.min(...ys)}-${Math.max(...ys)}` : "");
let maxC = 0; for (const i of inView) maxC = Math.max(maxC, C[i]);
console.log("maxC in view", maxC.toFixed(3), "nearest bad tile dist", inView.length ? Math.min(...inView.map((i) => Math.hypot(i % W - st.x, Math.floor(i / W) - st.y))).toFixed(1) : "-");
for (const f of r.features as any[]) if (/bad/i.test(f.id) || /bad/i.test(f.kind ?? "")) console.log("feature", f.id, JSON.stringify(f.params ?? {}).slice(0, 200));
console.log("guess?", JSON.stringify((r.info as any).plannedStart ?? null));
