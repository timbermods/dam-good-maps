const median = (v) => {
  if (!v.length) return NaN;
  const s = v.slice().sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const mean = (v) => (v.length ? v.reduce((a, b) => a + b, 0) / v.length : NaN);
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function bootstrap(pairs, stat, n = 2000) {
  // 90% interval of stat(pairs) over resamples of the maps
  if (pairs.length < 3) return [NaN, NaN];
  const rand = rng(12345);
  const out = [];
  for (let k = 0; k < n; k++) {
    const s = [];
    for (let i = 0; i < pairs.length; i++) s.push(pairs[Math.floor(rand() * pairs.length)]);
    out.push(stat(s));
  }
  out.sort((a, b) => a - b);
  return [out[Math.floor(0.05 * n)], out[Math.floor(0.95 * n)]];
}

// ------------------------------------------------------------------------------------ the machine's load

const mon = { samples: [], active: 0, last: null, timer: null, file: null };
function cpuNow() {
  let idle = 0;
  let total = 0;
  for (const c of os.cpus()) {
    for (const k of Object.keys(c.times)) total += c.times[k];
    idle += c.times.idle;
  }
  return { idle, total };
}
function startMonitor(file) {
  mon.file = file;
  mon.last = cpuNow();
  mon.timer = setInterval(() => {
    const n = cpuNow();
    const dt = n.total - mon.last.total;
    const busy = dt > 0 ? 100 * (1 - (n.idle - mon.last.idle) / dt) : 0;
    mon.last = n;
    const s = { t: Date.now(), busy: Math.round(busy * 10) / 10, active: mon.active };
    s.foreign = Math.max(0, Math.round((busy - (100 * mon.active * T.ownPerRun) / THREADS) * 10) / 10);
    mon.samples.push(s);
    if (mon.file) appendFileSync(mon.file, JSON.stringify(s) + '\n');
  }, 1000);
}
function stopMonitor() {
  clearInterval(mon.timer);
}
const loadOver = (t0, t1) => {
  let s = mon.samples.filter((x) => x.t > t0 && x.t <= t1 + 1000);
  if (!s.length) s = mon.samples.slice(-1);
  if (!s.length) return null;
  const b = s.map((x) => x.busy);
  const f = s.map((x) => x.foreign);
  return { mean: Math.round(mean(b) * 10) / 10, peak: Math.max(...b), foreignMean: Math.round(mean(f) * 10) / 10, foreignPeak: Math.max(...f), n: s.length };
};
const recentForeign = (secs) => {
  const s = mon.samples.slice(-secs);
  return s.length ? mean(s.map((x) => x.foreign)) : 0;
};

// Other processes that would disturb a timing (Windows: CIM; elsewhere ps). Own descendants and ancestors don't count.
function processes() {
  const parse = (j) => (Array.isArray(j) ? j : j ? [j] : []);
  try {
    if (process.platform === 'win32') {
      const ps = "Get-CimInstance Win32_Process | ForEach-Object { [pscustomobject]@{ pid = $_.ProcessId; ppid = $_.ParentProcessId; name = $_.Name; cmd = $_.CommandLine; cpu = [double]($_.KernelModeTime + $_.UserModeTime) } } | ConvertTo-Json -Compress";
      const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', ps], { encoding: 'utf8', maxBuffer: 1 << 26 });
      return parse(JSON.parse(r.stdout)).map((p) => ({ ...p, cpu: p.cpu / 1e7 })); // seconds of CPU
    }
    const r = spawnSync('ps', ['-A', '-o', 'pid=,ppid=,comm=,cputimes=,args='], { encoding: 'utf8', maxBuffer: 1 << 26 });
    return r.stdout.split('\n').filter(Boolean).map((l) => {
      const m = /^\s*(\d+)\s+(\d+)\s+(\S+)\s+(\d+)\s+(.*)$/.exec(l);
      return m ? { pid: +m[1], ppid: +m[2], name: m[3], cpu: +m[4], cmd: m[5] } : null;
    }).filter(Boolean);
  } catch {
    return null;
  }
}
const WATCHED = /^(node|chrome|chromium|msedge|firefox|electron|vitest|playwright|cargo|rustc|python|esbuild|dotnet|tsc|git)(\.exe)?$/i;
const ALWAYS = /vitest|playwright|\btsc\b|vite build|vite\.js|cargo|rustc|timberborn|workspace\.exe/i;
async function otherHeavy() {
  const a = processes();
  if (!a) return { ok: true, notes: ['process list unavailable: only the CPU load was checked'], busy: [] };
  const t0 = Date.now();
  await sleep(3000);
  const b = processes();
  const dt = (Date.now() - t0) / 1000;
  const byPid = new Map(b.map((p) => [p.pid, p]));
  const mine = new Set([process.pid]);
  for (let grew = true; grew; ) {
    grew = false;
    for (const p of b) if (mine.has(p.ppid) && !mine.has(p.pid)) (mine.add(p.pid), (grew = true));
  }
  const ancestors = new Set();
  for (let p = byPid.get(process.pid); p && p.ppid && !ancestors.has(p.ppid); p = byPid.get(p.ppid)) ancestors.add(p.ppid);
  const before = new Map(a.map((p) => [p.pid, p]));
  const busy = [];
  const idle = [];
  for (const p of b) {
    if (mine.has(p.pid)) continue;
    const timberborn = /timberborn/i.test(p.name);
    const watched = WATCHED.test(p.name) || timberborn;
    if (!watched) continue;
    const pct = before.has(p.pid) ? (100 * (p.cpu - before.get(p.pid).cpu)) / dt : 0;
    const where = (/DamGoodMaps[-\w]*/i.exec(p.cmd ?? '') ?? [''])[0];
    const row = { pid: p.pid, name: p.name, pct: Math.round(pct * 10) / 10, where, cmd: String(p.cmd ?? '').slice(0, 110) };
    if (ancestors.has(p.pid)) {
      if (pct >= T.busyProcess) busy.push({ ...row, why: 'an ancestor of this runner, busy' });
      continue;
    }
    if (timberborn) busy.push({ ...row, why: 'Timberborn is running' });
    else if (pct >= T.busyProcess) busy.push({ ...row, why: 'busy' });
    else if (ALWAYS.test(p.cmd ?? '')) busy.push({ ...row, why: 'a test/build tool is running' });
    else idle.push(row);
  }
  return { ok: !busy.length, busy, notes: idle.length ? [`${idle.length} idle watched process(es) ignored: ${idle.slice(0, 6).map((p) => `${p.name}#${p.pid}${p.where ? ' ' + p.where : ''}`).join(', ')}`] : [] };
}

async function waitQuiet(label, log, maxMin, windowMin) {
  // true when quiet (mean and peak load under the thresholds for windowMin, and nothing else heavy); false on giving up
  const t0 = Date.now();
  let lastSay = 0;
  for (;;) {
    const need = windowMin * 60;
    const w = mon.samples.slice(-need);
    const full = w.length >= need && w[w.length - 1].t - w[0].t >= (need - 3) * 1000;
    const m = w.length ? mean(w.map((x) => x.busy)) : 100;
    const pk = w.length ? Math.max(...w.map((x) => x.busy)) : 100;
    let procs = { ok: true, busy: [], notes: [] };
    if (full && m <= T.loadMean && pk <= T.loadPeak) procs = await otherHeavy();
    const quiet = full && m <= T.loadMean && pk <= T.loadPeak && procs.ok;
    if (quiet) {
      log(`${label}: quiet (load ${m.toFixed(1)}% mean, ${pk.toFixed(0)}% peak over ${windowMin} min)${procs.notes.length ? '; ' + procs.notes.join('; ') : ''}`);
      return true;
    }
    if (Date.now() - t0 > maxMin * 60000) {
      log(`${label}: GAVE UP after ${maxMin} min: the machine was not quiet (load ${m.toFixed(1)}% mean, ${pk.toFixed(0)}% peak; limits ${T.loadMean}% / ${T.loadPeak}%)${procs.busy.length ? '; ' + procs.busy.map((p) => `${p.name}#${p.pid} ${p.pct}% ${p.why} ${p.where}`).join('; ') : ''}`);
      return false;
    }
    if (Date.now() - lastSay > 60000) {
      lastSay = Date.now();
      log(`${label}: waiting for quiet (load ${m.toFixed(1)}% mean / ${pk.toFixed(0)}% peak over the last ${Math.min(windowMin, Math.round(w.length / 60 * 10) / 10)} min${full ? '' : ', window filling'})${procs.busy.length ? '; ' + procs.busy.map((p) => `${p.name}#${p.pid} ${p.pct}% ${p.why} ${p.where}`).join('; ') : ''}`);
    }
    await sleep(5000);
  }
}

// ------------------------------------------------------------------------------------ the snapshots

function prepareSnapshots(variants, names, snapRoot, log) {
  mkdirSync(snapRoot, { recursive: true });
  const out = {};
  for (const name of names) {
    const v = variants[name];
    const sha = git(['rev-parse', '--verify', `${v.ref}^{commit}`]).trim();
    const patchHash = v.patch ? createHash('sha256').update(readFileSync(v.patch)).digest('hex').slice(0, 8) : '';
    const dir = path.join(snapRoot, `${name.replace(/\W+/g, '_')}-${sha.slice(0, 12)}${patchHash ? '-p' + patchHash : ''}`);
    out[name] = { dir, sha, ref: v.ref, patch: !!v.patch, label: v.label };
    if (existsSync(path.join(dir, 'src/core/gen/generate.ts'))) continue;
    log(`snapshot ${name}: ${v.ref} (${sha.slice(0, 8)})${v.patch ? ' + patch' : ''} -> ${path.relative(ROOT, dir)}`);
    const tmp = mkdtempSync(path.join(os.tmpdir(), 'dgm-qw-'));
    try {
      // (tar reads "C:" as a host name, so it runs inside the folder with relative names)
      const tar = path.join(tmp, 'src.tar');
      git(['archive', '--format=tar', '-o', tar, sha, 'src/core']);
      const r = spawnSync('tar', ['-xf', 'src.tar'], { cwd: tmp, encoding: 'utf8' });
      if (r.status !== 0) throw new Error(`tar failed: ${r.stderr}`);
      rmSync(tar);
      if (v.patch) {
        // (outside any repository, so the patch's paths are taken as they are)
        const a = spawnSync('git', ['apply', '--ignore-space-change', v.patch], { cwd: tmp, encoding: 'utf8' });
        if (a.status !== 0) throw new Error(`${path.basename(v.patch)} does not apply to ${sha.slice(0, 8)}: ${a.stderr}\nThe tip has moved: port the patch's generate.ts hunk (it is one call after leanGenome) and regenerate the patch.`);
      }
      mkdirSync(dir, { recursive: true });
      cpSync(path.join(tmp, 'src'), path.join(dir, 'src'), { recursive: true });
    } finally {
      rmSync(tmp, { recursive: true, force: true });
    }
  }
  return out;
}

// ------------------------------------------------------------------------------------ worker handles

class Worker {
  constructor(name, snap) {
    this.name = name;
    this.snap = snap;
    this.seq = 0;
    this.pending = new Map();
    this.dead = false;
  }
  start() {
    return new Promise((resolve, reject) => {
      const nodePath = [path.join(ROOT, 'node_modules'), process.env.NODE_PATH].filter(Boolean).join(path.delimiter);
      this.proc = fork(fileURLToPath(import.meta.url), ['--child', '--snap', this.snap.dir], {
        execArgv: ['--expose-gc', '--max-old-space-size=6144'],
        env: { ...process.env, NODE_PATH: nodePath },
        stdio: ['ignore', 'inherit', 'inherit', 'ipc'],
      });
      this.proc.on('message', (m) => {
        if (m.id === 'ready') return resolve();
        const p = this.pending.get(m.id);
        if (p) (this.pending.delete(m.id), p(m));
      });
      this.proc.on('exit', (code) => {
        this.dead = true;
        for (const [, p] of this.pending) p({ error: `worker exited (${code})` });
        this.pending.clear();
        reject(new Error(`worker ${this.name} exited (${code}) before it was ready`));
      });
    });
  }
  run(job, timeoutMs) {
    return new Promise((resolve) => {
      const id = ++this.seq;
      const timer = setTimeout(() => {
        this.pending.delete(id);
        this.proc.kill();
        resolve({ error: `timeout after ${timeoutMs / 1000} s` });
      }, timeoutMs);
      this.pending.set(id, (m) => (clearTimeout(timer), resolve(m)));
      this.proc.send({ id, ...job });
    });
  }
  stop() {
    this.proc.removeAllListeners('exit');
    this.proc.kill();
  }
}

