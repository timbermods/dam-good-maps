// M9b's quiet-window timings, in one command (PLAN §20 D380: M9b must not release slower than `dev` at 256²).
//
//   node investigation/m9b/quiet-window.mjs                  the whole run (about 2 hours; --plan says exactly)
//   node investigation/m9b/quiet-window.mjs --plan           the work counts and the estimated time; times nothing
//   node investigation/m9b/quiet-window.mjs --smoke          tiny inputs through the whole pipeline (not timings)
//   node investigation/m9b/quiet-window.mjs --summarize DIR  the summary again from a run's results
//
// Run it only in the window Kyler names, with nothing else heavy on the machine: it waits for the
// machine to be quiet first (CPU load low for a minute, no other vitest/playwright/tsc/Timberborn, no busy
// node/chrome/browser/python/cargo process) and gives up after --wait-max-min (default 90) saying so. While
// it runs it watches the load, pauses when something else starts (and gives up after --pause-max-min), and
// marks any timing taken under foreign load as noisy; a noisy unit is run again once.
//
// What it times (each map generated by a persistent, warmed-up process per variant, the variants of one
// map taken one after the other in a rotating order, three repeats, `gc()` before each; CPU is the
// process's CPU time, wall the call's, first look the first `onLand`):
//
//   large  256², all seven themes, seeds 1-8:  dev, ss, r1, r2, tip       (timing 4: tip against dev, D380;
//                                                                          round 1 = ss -> r1; round 2 = r1 -> r2)
//   lake   Lake Basin, seeds 1-20, 96² 128² 256²:  tip, tip+lb             (timing 3: Lake Basin round 2)
//   small  96² and 128², all themes, seeds 1-8:  pre-ss, ss, r1, r2, tip   (timing 1: small starts' first look
//                                                                          pre-ss -> tip; timing 2 at the small sizes)
//
//   variant  state                                                      ref
//   pre-ss   before small starts (dev merged, one mine-site check)      4a785170
//   ss       + small starts (#153)                                      affe89b9
//   r1       + generation speed round 1 (#155)                          37e144b2
//   r2       + generation speed round 2 (#155)                          892cc5c2
//   tip      the branch as it is (the 128² gate and everything since)   HEAD (--tip REF)
//   tip+lb   tip + Lake Basin round 2 (quiet-window/lake-basin-round2.patch, ported to the tip)
//   dev      origin/dev (--dev REF)
//
// Results: investigation/m9b/local/quiet-window/<stamp>/ (gitignored, D195): results.jsonl (every timing, with
// the machine's load beside it), warmups.jsonl, load.jsonl (the load, one line per second), gates.log,
// config.json and summary.md (also printed). The snapshots of each ref's src/core are built once, into
// local/quiet-window/snaps/, and kept. Once per machine: npm ci (typescript and fflate from the root's
