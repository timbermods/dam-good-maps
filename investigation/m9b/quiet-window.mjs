function mapSeconds(variant, theme, size) {
  return MAP_S[size][theme] * FACTOR * (VARIANT_FACTOR[variant] ?? 1);
}
function estimate(groups, lanes) {
  const rows = [];
  let total = 90; // snapshots, the quiet minute, the process check
  for (const [name, g] of Object.entries(groups)) {
    const maps = g.sizes.length * g.themes.length * g.seeds.length;
    let lane = 0;
    for (const size of g.sizes) for (const theme of g.themes) for (const v of g.variants) lane += g.seeds.length * g.reps * mapSeconds(v, theme, size);
    let warm = 0;
    for (const v of g.variants) for (const size of g.sizes) warm += mapSeconds(v, g.themes[0], size) + 6; // the warm-up map and loading the source
    const tail = g.sizes.includes(256) ? 90 : 20; // the last long map, no lane to share it with
    const wall = (lane / lanes) * 1.07 + warm + tail + 60; // 7% for the noisy units run again
    rows.push({ name, maps, runs: maps * g.reps * g.variants.length, lane, warm, wall });
    total += wall;
  }
  return { rows, total };
}
function planText(groups, lanes) {
  const e = estimate(groups, lanes);
  const lines = [`Estimated on this machine when quiet (${THREADS} threads, ${lanes} lanes), from the work counts: maps x reps x variants x per-map seconds`,
    `(gen-speed round 2's per-theme medians x ${FACTOR}, which matches this machine's quiet 128² and 256² medians in docs/progress/m9b.md; Lake Basin round 2 taken 1.5x; +7% for noisy reruns; +warm-ups; accuracy about +-30%):`, ''];
  lines.push('| group | maps | timed runs | lane-seconds | wall |', '|---|---:|---:|---:|---:|');
  for (const r of e.rows) lines.push(`| ${r.name} (${groups[r.name].variants.join(', ')}; ${groups[r.name].sizes.join('/')}²; ${groups[r.name].themes.length} theme(s) x ${groups[r.name].seeds.length} seeds x ${groups[r.name].reps} reps) | ${r.maps} | ${r.runs} | ${Math.round(r.lane)} | ${hhmm(r.wall * 1000)} |`);
  lines.push(`| setup (snapshots, quiet check) | | | | 1.5 min |`, `| **total** | | ${e.rows.reduce((a, r) => a + r.runs, 0)} | | **${hhmm(e.total * 1000)}** |`);
  return lines.join('\n');
}

// ------------------------------------------------------------------------------------ the run

async function main() {
  if (has('summarize')) {
    const dir = path.resolve(arg('summarize', ''));
    const text = summarize(dir);
    writeFileSync(path.join(dir, 'summary.md'), text);
    console.log(text);
    return;
  }
  const smoke = has('smoke');
  const tipRef = arg('tip', 'HEAD');
  const devRef = arg('dev', 'origin/dev');
  const lanes = Math.max(1, Number(arg('lanes', smoke ? 2 : 3)));
  const only = arg('only', '').split(',').filter(Boolean);
  const groups = {};
  for (const [name, g0] of Object.entries(GROUPS)) {
    if (only.length && !only.includes(name)) continue;
    const g = { ...g0 };
    if (smoke) Object.assign(g, { sizes: [96], themes: g.themes.length === 1 ? g.themes : ['delta', 'riverValley'], seeds: [1, 2], reps: 2 });
    if (has('reps')) g.reps = Number(arg('reps', 3));
    if (has('sizes')) g.sizes = arg('sizes', '').split(',').map(Number);
    if (has('themes')) g.themes = arg('themes', '').split(',');
    if (has('seeds')) {
      const m = /^(\d+)-(\d+)$/.exec(arg('seeds', ''));
      g.seeds = m ? range(+m[1], +m[2]) : arg('seeds', '').split(',').map(Number);
    }
    if (name === 'lake' && has('themes')) g.themes = g.themes.filter((t) => t === 'lakeBasin');
    groups[name] = g;
  }
  if (!Object.keys(groups).length) throw new Error('no group selected');
  if (has('plan')) {
    console.log(planText(groups, lanes));
    return;
  }

  if (has('fetch')) git(['fetch', 'origin', 'dev', 'feature/m9b']);
  const variants = variantsOf(tipRef, devRef);
  const needed = [...new Set(Object.values(groups).flatMap((g) => g.variants))];
  const runName = (smoke ? 'smoke-' : '') + stamp();
  const dir = has('resume') ? path.resolve(arg('resume', '')) : path.join(ROOT, 'investigation/m9b/local/quiet-window', runName);
  mkdirSync(dir, { recursive: true });
  const logFile = path.join(dir, 'gates.log');
  const log = (s) => {
    const line = `[${new Date().toTimeString().slice(0, 8)}] ${s}`;
    console.log(line);
    appendFileSync(logFile, line + '\n');
  };
  log(`${smoke ? 'SMOKE RUN (tiny inputs, not timings) ' : ''}quiet-window runner, results in ${path.relative(ROOT, dir)}`);
  const snaps = prepareSnapshots(variants, needed, path.join(ROOT, 'investigation/m9b/local/quiet-window/snaps'), log);
  const est = estimate(groups, lanes);
  log(`estimated duration ${hhmm(est.total * 1000)} (--plan for the breakdown)`);
  writeFileSync(path.join(dir, 'config.json'), JSON.stringify({
    started: new Date().toISOString(), smoke, lanes, groups, snaps: Object.fromEntries(Object.entries(snaps).map(([k, v]) => [k, { ref: v.ref, sha: v.sha, patch: v.patch, label: v.label }])),
    machine: { cpu: os.cpus()[0].model.trim(), threads: THREADS, mem: Math.round(os.totalmem() / 2 ** 30) + ' GiB', node: process.version, platform: process.platform },
    thresholds: T, estimateSeconds: Math.round(est.total),
  }, null, 2));

  startMonitor(path.join(dir, 'load.jsonl'));
  const resultsFile = path.join(dir, 'results.jsonl');
  const warmFile = path.join(dir, 'warmups.jsonl');
  const done = new Set();
  if (has('resume') && existsSync(resultsFile))
    for (const l of readFileSync(resultsFile, 'utf8').split('\n')) if (l.startsWith('{')) {
      const r = JSON.parse(l);
      if (!r.error && !r.noisy) done.add(`${r.g}|${r.v}|${r.theme}|${r.size}|${r.seed}|${r.rep}`);
    }
  const unchecked = smoke || has('skip-quiet-check');
  const t0 = Date.now();
  const budgetMs = has('budget-min') ? Number(arg('budget-min', 0)) * 60000 : Infinity;
  const pauseMax = Number(arg('pause-max-min', 20));
  let abort = '';
  let stoppedByBudget = false;
  const stop = (why) => {
    if (!abort) (abort = why, log(`STOPPING: ${why}`));
  };
  process.on('SIGINT', () => {
    stop('interrupted (Ctrl-C)');
  });

  // 1. the machine must be quiet before anything is timed
  if (smoke || has('skip-quiet-check')) log(has('skip-quiet-check') ? 'WARNING: --skip-quiet-check, the machine was NOT checked; these are not decision timings' : 'smoke: the quiet check is skipped');
  else if (!(await waitQuiet('start', log, Number(arg('wait-max-min', 90)), T.quietMinutes))) {
    stopMonitor();
    log('nothing was timed. Run it again when nothing else is running.');
    process.exitCode = 3;
    return;
  }

  for (const [gname, g] of Object.entries(groups)) {
    if (abort) break;
    if (!smoke && !has('skip-quiet-check') && gname !== Object.keys(groups)[0] && !(await waitQuiet(`before ${gname}`, log, Number(arg('wait-max-min', 90)), 0.5))) {
      stop('the machine did not go quiet before group ' + gname);
      break;
    }
    log(`group ${gname}: ${g.variants.join(', ')} at ${g.sizes.join('/')}², ${g.themes.length} theme(s), seeds ${g.seeds[0]}-${g.seeds[g.seeds.length - 1]}, ${g.reps} reps, ${lanes} lanes`);
    // units: one map, one rep; rep-major so an early end still has balanced coverage; the long maps first within a rep
    const units = [];
    for (let rep = 1; rep <= g.reps; rep++) {
      const list = [];
      for (const size of g.sizes) for (const theme of g.themes) for (const seed of g.seeds) list.push({ size, theme, seed, rep, attempt: 1 });
      list.sort((a, b) => b.size - a.size);
      units.push(...list);
    }
    const queue = units.filter((u) => g.variants.some((v) => !done.has(`${gname}|${v}|${u.theme}|${u.size}|${u.seed}|${u.rep}`)));
    const retry = [];
    let index = 0;
    let finished = 0;
    let retried = 0;
    const total = queue.length;
    const lane = async (laneNo) => {
      const workers = {};
      try {
        // (the warm-up: a few maps through each variant's own process, one per size, before any timing)
        for (const v of g.variants) {
          const w = new Worker(v, snaps[v]);
          await w.start();
          workers[v] = w;
          mon.active++;
          for (const size of g.sizes) {
            const a = Date.now();
            const r = await w.run({ theme: g.themes[0], seed: 101, size }, 600000);
            appendFileSync(warmFile, JSON.stringify({ g: gname, v, lane: laneNo, theme: g.themes[0], size, ...r, t: new Date().toISOString(), took: Date.now() - a }) + '\n');
            if (r.error) log(`warm-up ${v} ${size}² failed: ${r.error.split('\n')[0]}`);
          }
          mon.active--;
        }
        for (;;) {
          if (abort) return;
          if (Date.now() - t0 > budgetMs) {
            stoppedByBudget = true;
            return;
          }
          const u = queue.length ? queue.shift() : retry.shift();
          if (!u) return;
          const k = index++;
          // pause while something else is running
          const w0 = Date.now();
          while (!unchecked && recentForeign(10) > T.pauseForeign && !abort) {
            if (Date.now() - w0 > pauseMax * 60000) {
              stop(`foreign load stayed above ${T.pauseForeign}% for ${pauseMax} min`);
              return;
            }
            if ((Date.now() - w0) % 60000 < 2100) log(`lane ${laneNo}: paused, foreign load ${recentForeign(10).toFixed(0)}%`);
            await sleep(2000);
          }
          const order = g.variants.map((_, i) => g.variants[(i + k + u.rep) % g.variants.length]);
          let noisy = false;
          for (const v of order) {
            if (abort) return;
            if (u.attempt === 1 && done.has(`${gname}|${v}|${u.theme}|${u.size}|${u.seed}|${u.rep}`)) continue;
            const a = Date.now();
            mon.active++;
            const r = await workers[v].run({ theme: u.theme, seed: u.seed, size: u.size }, 900000);
            mon.active--;
            const b = Date.now();
            const load = loadOver(a, b);
            const isNoisy = !!load && (load.foreignMean > T.noisyMean || load.foreignPeak > T.noisyPeak);
            noisy ||= isNoisy;
            const rec = { g: gname, v, theme: u.theme, size: u.size, seed: u.seed, rep: u.rep, attempt: u.attempt, lane: laneNo, order: order.indexOf(v), t0: a, t1: b, load, noisy: isNoisy, ...r };
            appendFileSync(resultsFile, JSON.stringify(rec) + '\n');
            if (r.error) {
              log(`ERROR ${v} ${u.theme} ${u.size}² seed ${u.seed}: ${r.error.split('\n')[0]}`);
              if (workers[v].dead) {
                const w = new Worker(v, snaps[v]);
                await w.start();
                workers[v] = w;
              }
            }
          }
          if (noisy && u.attempt === 1) (retry.push({ ...u, attempt: 2 }), retried++);
          finished++;
          if (finished % 10 === 0 || finished === total)
            log(`${gname}: ${finished}/${total + retried} units, ${hhmm(Date.now() - t0)} elapsed, load now ${(mon.samples.at(-1)?.busy ?? 0).toFixed(0)}% (foreign ${recentForeign(10).toFixed(0)}%)`);
        }
      } catch (e) {
        stop(`lane ${laneNo} failed: ${String(e?.message ?? e).split('\n')[0]}`);
      } finally {
        for (const w of Object.values(workers)) if (!w.dead) w.stop();
      }
    };
    await Promise.all(range(1, lanes).map(lane));
    if (stoppedByBudget) {
      log(`budget of ${arg('budget-min', 0)} min reached: no new units; summarising what was timed`);
      break;
    }
  }
  stopMonitor();
  const text = summarize(dir, { smoke, abort, stoppedByBudget, elapsedMs: Date.now() - t0, quietChecked: !(smoke || has('skip-quiet-check')) });
  writeFileSync(path.join(dir, 'summary.md'), text);
  console.log('\n' + text);
  log(`done in ${hhmm(Date.now() - t0)}; ${path.relative(ROOT, path.join(dir, 'summary.md'))}`);
  if (abort) process.exitCode = 4;
}

// ------------------------------------------------------------------------------------ the summary

function summarize(dir, run = {}) {
  const lines0 = readFileSync(path.join(dir, 'results.jsonl'), 'utf8').split('\n').filter((l) => l.startsWith('{'));
  const recs = lines0.map((l) => JSON.parse(l));
  const cfg = existsSync(path.join(dir, 'config.json')) ? JSON.parse(readFileSync(path.join(dir, 'config.json'), 'utf8')) : null;
  const good = recs.filter((r) => !r.error);
  const errors = recs.filter((r) => r.error);
  // per (variant, map): the clean repeats (else all of them, flagged)
  const cells = new Map();
  for (const r of good) {
    const key = `${r.v}|${r.theme}|${r.size}|${r.seed}`;
    if (!cells.has(key)) cells.set(key, []);
    cells.get(key).push(r);
  }
  const cell = (key) => {
    const all = cells.get(key);
    if (!all) return null;
    const clean = all.filter((r) => !r.noisy);
    const use = clean.length ? clean : all;
    const m = (f) => median(use.map(f).filter((x) => x >= 0));
    const spread = (f) => {
      const v = use.map(f).filter((x) => x > 0);
      return v.length > 1 ? (Math.max(...v) - Math.min(...v)) / median(v) : NaN;
    };
    return {
      n: use.length,
      noisyOnly: !clean.length,
      'map wall': m((r) => r.wall),
      'map cpu': m((r) => r.cpu),
      'first look': m((r) => r.firstLook),
      'first look cpu': m((r) => r.firstLookCpu),
      spread: spread((r) => r.wall),
      hash: use.map((r) => r.hash).join(','),
      hashes: [...new Set(use.map((r) => r.hash))],
      ok: use.every((r) => r.ok),
    };
  };
  const out = [];
  const w = (s = '') => out.push(s);
  w(`# M9b quiet-window timings${run.smoke || cfg?.smoke ? ' (SMOKE: tiny inputs through the pipeline, not timings)' : ''}`);
  w();
  if (cfg) {
    w(`${cfg.machine.cpu}, ${cfg.machine.threads} threads, ${cfg.machine.mem}, Node ${cfg.machine.node}; ${cfg.lanes} lane(s); started ${cfg.started}.`);
    w(`Variants: ${Object.entries(cfg.snaps).map(([k, v]) => `${k} = ${v.ref}${v.ref.length < 12 ? '' : ''} (${v.sha.slice(0, 8)}${v.patch ? ' + patch' : ''})`).join('; ')}.`);
  }
  const loads = good.map((r) => r.load).filter(Boolean);
  const noisyN = good.filter((r) => r.noisy).length;
  const sampleFile = path.join(dir, 'load.jsonl');
  const lsamples = existsSync(sampleFile) ? readFileSync(sampleFile, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [];
  w(`Timed runs: ${good.length}${errors.length ? `, ${errors.length} failed` : ''}; machine load while timing: mean ${mean(loads.map((l) => l.mean)).toFixed(1)}% (foreign, after our own lanes' share: ${mean(loads.map((l) => l.foreignMean)).toFixed(1)}% mean, worst second ${Math.max(0, ...loads.map((l) => l.foreignPeak)).toFixed(0)}%); noisy runs (foreign load over ${T.noisyMean}% mean or ${T.noisyPeak}% for a second) ${noisyN}, run again where they could be.`);
  if (lsamples.length) w(`Whole-run load: mean ${mean(lsamples.map((s) => s.busy)).toFixed(1)}%, foreign mean ${mean(lsamples.map((s) => s.foreign)).toFixed(1)}%, p95 foreign ${lsamples.map((s) => s.foreign).sort((a, b) => a - b)[Math.floor(0.95 * lsamples.length)]}%.`);
  if (run.quietChecked === false) w('**The quiet check was skipped: not decision timings.**');
  if (run.abort) w(`**Stopped early: ${run.abort}.** The table is what was timed.`);
  if (run.stoppedByBudget) w('**Stopped at the time budget; the table is what was timed.**');
  if (errors.length) w(`Errors: ${[...new Set(errors.map((e) => `${e.v}: ${e.error.split('\n')[0]}`))].slice(0, 5).join(' | ')}`);
  w();
  w('Times are per map in seconds, median over the maps of each map\'s median over its clean repeats. Ratio = after / before for the same map, over the maps both variants timed: the median of the per-map ratios [90% bootstrap interval over maps], and the ratio of the mean times (the time per map in production) [interval]. A change is called slower or faster only when the interval of the ratio of means excludes 1.');
  w();
  const verdicts = [];
  for (const c of COMPARISONS) {
    const sizes = (cfg?.smoke ? [96, 128, 256] : c.sizes).filter((s) => [...cells.keys()].some((k) => k.startsWith(c.a + '|') && k.split('|')[2] == s) && [...cells.keys()].some((k) => k.startsWith(c.b + '|') && k.split('|')[2] == s));
    if (!sizes.length) continue;
    w(`## ${c.id}`);
    w();
    w('| size | metric | maps | before median | after median | median ratio [90%] | mean before | mean after | ratio of means [90%] | rep spread before / after | same bytes | verdict |');
    w('|---|---|---:|---:|---:|---|---:|---:|---|---|---:|---|');
    for (const size of sizes) {
      const keys = [...cells.keys()].filter((k) => k.startsWith(c.a + '|') && k.split('|')[2] == size).map((k) => k.slice(c.a.length + 1));
      const maps = keys.filter((k) => cells.has(`${c.b}|${k}`));
      const cellsA = maps.map((k) => cell(`${c.a}|${k}`));
      const cellsB = maps.map((k) => cell(`${c.b}|${k}`));
      const same = maps.filter((_, i) => cellsA[i].hashes.length === 1 && cellsB[i].hashes.length === 1 && cellsA[i].hashes[0] === cellsB[i].hashes[0] && cellsA[i].hashes[0] !== '').length;
      for (const metric of c.metrics) {
        const pairs = maps.map((_, i) => [cellsA[i][metric], cellsB[i][metric]]).filter(([a, b]) => a > 0 && b > 0 && isFinite(a) && isFinite(b));
        if (!pairs.length) continue;
        const s = (ms) => (ms / 1000).toFixed(2);
        const medA = median(pairs.map((p) => p[0]));
        const medB = median(pairs.map((p) => p[1]));
        const mnA = mean(pairs.map((p) => p[0]));
        const mnB = mean(pairs.map((p) => p[1]));
        const rMed = (ps) => median(ps.map(([a, b]) => b / a));
        const rMean = (ps) => mean(ps.map((p) => p[1])) / mean(ps.map((p) => p[0]));
        const ciMed = bootstrap(pairs, rMed);
        const ciMean = bootstrap(pairs, rMean);
        const f = (x) => (isFinite(x) ? x.toFixed(3) : 'n/a');
        const verdict = ciMean[0] > 1 ? 'SLOWER' : ciMean[1] < 1 ? 'faster' : 'no clear difference';
        const spA = median(cellsA.map((x) => x.spread).filter(isFinite));
        const spB = median(cellsB.map((x) => x.spread).filter(isFinite));
        const noisyCells = cellsA.concat(cellsB).filter((x) => x.noisyOnly).length;
        w(`| ${size}² | ${metric} | ${pairs.length}${noisyCells ? ` (${noisyCells} noisy cells)` : ''} | ${s(medA)} | ${s(medB)} | ${f(rMed(pairs))} [${f(ciMed[0])}, ${f(ciMed[1])}] | ${s(mnA)} | ${s(mnB)} | ${f(rMean(pairs))} [${f(ciMean[0])}, ${f(ciMean[1])}] | ${isFinite(spA) ? (100 * spA).toFixed(1) + '%' : 'n/a'} / ${isFinite(spB) ? (100 * spB).toFixed(1) + '%' : 'n/a'} | ${same}/${maps.length} | ${verdict} |`);
        verdicts.push({ id: c.id, size, metric, verdict, ratio: rMean(pairs), n: pairs.length });
      }
    }
    w();
    // per theme at 256² for the comparisons that decide something
    if (sizes.includes(256) && (c.a === 'dev' || c.a === 'tip')) {
      w(`By theme at 256² (map wall, median of the maps, seconds):`);
      w();
      w(`| theme | maps | ${c.a} | ${c.b} | ratio of means |`);
      w('|---|---:|---:|---:|---:|');
      for (const theme of ALL_THEMES) {
        const ks = [...cells.keys()].filter((k) => k.startsWith(c.a + `|${theme}|256|`)).map((k) => k.slice(c.a.length + 1)).filter((k) => cells.has(`${c.b}|${k}`));
        if (!ks.length) continue;
        const A = ks.map((k) => cell(`${c.a}|${k}`)['map wall']);
        const B = ks.map((k) => cell(`${c.b}|${k}`)['map wall']);
        w(`| ${theme} | ${ks.length} | ${(median(A) / 1000).toFixed(2)} | ${(median(B) / 1000).toFixed(2)} | ${(mean(B) / mean(A)).toFixed(3)} |`);
      }
      w();
    }
  }
  w('## One line each');
  w();
  const pick = (id, metric, size) => verdicts.find((v) => v.id.startsWith(id) && v.metric === metric && v.size === size);
  const one = (id, label, metrics) => {
    const parts = verdicts.filter((v) => v.id.startsWith(id) && metrics.includes(v.metric)).map((v) => `${v.size}² ${v.metric} x${v.ratio.toFixed(3)} (${v.verdict}, ${v.n} maps)`);
    w(`- ${label}: ${parts.length ? parts.join('; ') : 'not timed'}`);
  };
  void pick;
  one('T1', 'Small starts, first look, after / before', ['first look']);
  one('T2a', 'Round 1, CPU per map', ['map cpu']);
  one('T2a', 'Round 1, wall per map', ['map wall']);
  one('T2b', 'Round 2, CPU per map', ['map cpu']);
  one('T2b', 'Round 2, wall per map', ['map wall']);
  one('T3', 'Lake Basin round 2, wall per map', ['map wall']);
  one('T4', 'Tip against dev at 256², wall per map', ['map wall']);
  one('T4', 'Tip against dev at 256², CPU per map', ['map cpu']);
  w();
  const rs = recs.filter((r) => !r.error && r.v !== undefined);
  w(`Raw: ${path.relative(ROOT, path.join(dir, 'results.jsonl'))} (${rs.length} timed runs, each with its load); load.jsonl (one line per second); gates.log; warmups.jsonl.`);
  return out.join('\n') + '\n';
}

